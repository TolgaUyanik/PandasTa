    """A tier-2 `have` row must be backed by a recorded comparison.

    There used to be a second hand-maintained list here, `DOCSTRING_AUDITED`,
    duplicating the generator's own `AUDITED` map with nothing keeping them in
    step -- and 13 of its names had been certified on the library's one-line
    `@function` summary alone. Round 7 showed what that is worth: `trima`,
    `stc`, `aroon` and `kvo` were all on such a list and all diverge. There is
    now one source of truth, `gen.AUDITED`, and it stores evidence rather than
    names.
    """
    gen = _load_classifier()
    tier2_have = {r["name"] for r in _rows()
                  if r["verdict"] == "have"
                  and r["in_tradingview_ta_library"] == "1"}
    unaudited = sorted(tier2_have - set(gen.AUDITED))

    # Not an assertion that the backlog is empty: it is not, and saying
    # otherwise is the defect this whole thread of findings is about. What is

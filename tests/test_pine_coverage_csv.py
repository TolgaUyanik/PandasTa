def test_audited_rows_carry_their_evidence():
    """`audited=yes` must cite a line that actually carries the claim.

    Three rounds of escalation on one point. Round 6 required a NAME, and four
    of twenty-nine names were divergent. Round 7 required a `file:line`-SHAPED
    string, and never opened the file -- so seven of fifteen receipts pointed at
    the wrong line and one (`variance`) asserted a divergence that does not
    exist, being `stdev`'s caveat pasted across without running the code.

    This opens the file. Every `<path>:<n>` in the receipt must resolve, `n`
    must be in range, and the receipt's backticked token must appear within two
    lines of `n`. A fabricated citation now fails.
    """
    for row in _rows():
        if row["audited"] != "yes":
            assert row["audit_evidence"] == "", (
                f"{row['name']}: evidence recorded but audited={row['audited']}"
            )
            continue

        evidence = row["audit_evidence"]
        assert len(evidence) > 30, f"{row['name']}: evidence too thin: {evidence!r}"

        # PAIRED form: `path:line` immediately followed by the backticked
        # token that carries the claim. An earlier version collected citations
        # and tokens separately and asked `any(token in line)`, which a
        # deliberately wrong-but-in-range citation survived because an
        # incidental backticked word elsewhere in the prose ("unlike
        # `variance`") happened to appear at the wrong line.
        pairs = re.findall(
            r"([\w/.-]+\.(?:py|pine)):(\d+)[\s\-–—]*`([^`]+)`", evidence)
        assert pairs, (
            f"{row['name']}: evidence has no `path:line `token`` pair, so "
            f"there is nothing to check -- {evidence!r}"
        )

        checked_a_repo_file = False
        for path, lineno, token in pairs:
            full = os.path.join(_FORK, path)
            if not os.path.exists(full):          # the library .pine lives in docs/pine
                full = os.path.join(DOCS, "pine", os.path.basename(path))
            assert os.path.exists(full), (
                f"{row['name']}: the receipt cites {path}, which resolves to no "
                f"file in this repo. A citation nobody can open is not evidence."
            )
            checked_a_repo_file = True
            lines = io.open(full, encoding="utf8", errors="replace").read().splitlines()
            n = int(lineno)
            assert 1 <= n <= len(lines), (
                f"{row['name']}: {path}:{n} is out of range (file has "
                f"{len(lines)} lines)"
            )
            assert token in lines[n - 1], (
                f"{row['name']}: the receipt's token {token!r} is not ON "
                f"{path}:{n}. The citation does not carry the claim:"
                f"{chr(10)}  {lines[n - 1].strip()}"
            )
        assert checked_a_repo_file, (
            f"{row['name']}: no cited path resolved in the repo -- {evidence!r}"
        )



@pytest.mark.parametrize("verdict,block,next_block", [
    ("port", "PINEBI-1b", "PINEBI-1c"),
    ("port - alternate impl", "PINEBI-1c", "PINEBI-1d"),
])
def test_every_scoped_row_is_named_in_its_task(verdict, block, next_block):
    """A verdict routes a row to a task; the task must actually list it.

    `stc` was reported as "scoped into PINEBI-1b" for a whole round while
    existing only as the string `; PINEBI-1b` inside a CSV note. The split guard
    could not see it: that test reads markdown TABLES, and a scope written in
    prose is unguarded. This reads the task block itself.
    """
    todo = os.path.join(_FORK, "TODO.md")
    if not os.path.exists(todo):
        pytest.skip("TODO.md missing")
    text = io.open(todo, encoding="utf8").read()
    # Anchor on the task BLOCK, not the first bare mention. `text.index(block)`
    # matched the ACTIVE band's one-line summary ("**PINEBI-1c/-1d/-1e**"),
    # where the next tag follows immediately, so `body` was a ten-character
    # slice with no `ROWS:` line and the guard reported a real, present
    # enumeration as missing. Search for the thing, not the name -- the same
    # lesson the altrepo scanners keep teaching.
    def _block_start(tag, frm=0):
        for marker in (f"**{tag} —", f"**{tag} -", f"**{tag}"):
            i = text.find(marker, frm)
            if i != -1:
                return i
        return text.index(tag, frm)

    start = _block_start(block)
    body = text[start:_block_start(next_block, start)]

    expected = sorted(r["name"] for r in _rows() if r["verdict"] == verdict)

    # The ENUMERATION line, not "mentioned somewhere in the block". A prose
    # mention elsewhere in the same task satisfied the looser check during
    # mutation testing, so deleting a name from the list it is actually ported
    # from would have passed.
    # The scope's rows are declared on an explicit `ROWS:` line. Heuristics
    # failed twice: reading one line missed `stochFull`/`stochRsi` on a
    # continuation, and reading the whole region passed a deleted `stc` because
    # a prose sentence in the same region happened to mention it. A marker the
    # guard and the human both read removes the guessing.
    marker = [l for l in body.splitlines() if l.strip().startswith("ROWS:")]
    assert len(marker) == 1, (
        f"{block} must declare its rows on exactly one `ROWS:` line, found "
        f"{len(marker)}"
    )
    enumeration = set(re.findall(r"`([A-Za-z_][A-Za-z0-9_]*)`", marker[0]))

    missing = [n for n in expected if n not in enumeration]
    # Only flag names that belong to ANOTHER verdict bucket -- prose in the
    # region legitimately mentions functions and task ids.
    routed_elsewhere = {r["name"]: r["verdict"] for r in _rows()}
    extra = sorted(n for n in enumeration - set(expected)
                   if routed_elsewhere.get(n, verdict) != verdict)
    assert missing == [], (
        f"{block}'s list omits {missing}, which the CSV routes to it. A task "
        f"that does not list a row will not port it."
    )
    assert extra == [], (
        f"{block}'s list names {extra}, which the CSV does not route to it"
    )


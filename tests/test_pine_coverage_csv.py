"""PINEBI-0: the coverage CSV must stay reproducible from its classifier.

`docs/gen_pine_builtin_coverage.py` says in its own docstring that "the
classifier IS the artifact -- a changed count is not a finding, but a changed
VERDICT is". This makes that promise executable.

It exists because the promise was broken once, in a way that was invisible until
someone re-ran the script: PINEBI-1a landed the 18 primitives into
`pandas_ta.utils`, `classify()` consulted `equivalent()` before its `PRIMITIVES`
check, and fourteen rows silently flipped from `port - primitive` to `have` --
collapsing the split into two buckets and invalidating the CSV the four
downstream tasks are scoped from. The figures are deliberately NOT retyped
here: this docstring was itself one of the three places the split went
stale, and `test_no_other_document_retypes_the_split` now scans this file
along with every document in the fork. The fix was to make `PRIMITIVES`
outrank a namespace match; this test is the guard.

The corpus test is skipped when `docs/pine/` is absent — it is untracked by design
(2,211 files, 46MB, 912 of them MPL-2.0 © TradingView), so it exists on a
working checkout and not in CI. The other guards read the committed CSV and run
everywhere.
"""
import collections
import csv
import io
import os
import re
import subprocess
import sys

import pytest

_HERE = os.path.dirname(os.path.abspath(__file__))
_FORK = os.path.dirname(_HERE)
DOCS = os.path.join(_FORK, "docs")
CSV = os.path.join(DOCS, "pine_builtin_coverage.csv")
GEN = os.path.join(DOCS, "gen_pine_builtin_coverage.py")
CORPUS = os.path.join(DOCS, "pine")

# One definition of "a verdict-count claim", used by both split guards. It was
# inline in a single test; two tests reading the same shape must not drift.
TABLE_ROW = r"^\s*\|\s*`([A-Za-z0-9/ '\-]+)`[^|]*\|\s*(\d+)\s*\|\s*$"
NAMELESS_SPLIT = r"\b\d+(?:/\d+){4,}\b"

VERDICTS = {
    "have", "port", "port - primitive", "port - alternate impl",
    "port - blocked on data", "n/a - not a Pine built-in",
    "n/a - not worth a primitive", "n/a - never called live in the corpus",
}


def _rows():
    # NOT a skip. The CSV is a committed artifact that four task scopes are cut
    # from; if it is missing, the guards below would evaporate into skips and a
    # clone would report green while checking nothing. It was ignored by
    # `.gitignore`'s blanket `*.csv` until 2026-09-07, so this failed silently
    # for every reader but the author.
    assert os.path.exists(CSV), (
        f"{CSV} is missing. It is generated by docs/gen_pine_builtin_coverage.py "
        f"and MUST be committed -- see the `!docs/pine_builtin_coverage.csv` "
        f"line in .gitignore."
    )
    with open(CSV, encoding="utf8") as fh:
        return list(csv.DictReader(fh))


def test_every_row_has_a_known_verdict():
    """PINEBI-0's acceptance criterion: every function classified, none blank."""
    rows = _rows()
    assert rows, "the CSV is empty"
    unknown = sorted({r["verdict"] for r in rows} - VERDICTS)
    assert unknown == [], f"unrecognised verdicts: {unknown}"
    blank = [r["name"] for r in rows if not r["name"] or not r["verdict"]]
    assert blank == [], blank


def test_primitives_stay_primitives_after_they_land():
    """The exact regression that broke reproducibility once.

    All 18 are importable from `pandas_ta` now, so a classifier that checks the
    namespace before its own PRIMITIVES list calls them `have` and quietly
    retires the task that is supposed to produce them.
    """
    rows = {r["name"]: r for r in _rows()}
    landed = [n for n in ("highest", "lowest", "barssince", "valuewhen",
                          "percentrank", "pivothigh", "pivotlow", "cum")
              if n in rows]
    assert landed, "expected the core primitives in the CSV"
    for name in landed:
        assert rows[name]["verdict"] == "port - primitive", (
            f"{name} is classified {rows[name]['verdict']!r}; landing a "
            f"primitive must not reclassify it"
        )


@pytest.mark.skipif(not os.path.isdir(CORPUS),
                    reason="docs/pine corpus is untracked by design (licence)")
def test_regenerating_reproduces_the_committed_csv(tmp_path):
    """Re-run the classifier; the verdict column must not move.

    Counts may drift with the corpus and that is explicitly allowed. Verdicts
    may not: they are what the -1a..-1e scopes are cut from.
    """
    out = tmp_path / "regenerated.csv"
    proc = subprocess.run([sys.executable, GEN, str(out)],
                          capture_output=True, text=True, cwd=_FORK)
    assert proc.returncode == 0, proc.stderr[-2000:]

    with open(out, encoding="utf8") as fh:
        fresh = {r["name"]: r["verdict"] for r in csv.DictReader(fh)}
    committed = {r["name"]: r["verdict"] for r in _rows()}

    moved = {n: (committed[n], fresh[n]) for n in committed.keys() & fresh.keys()
             if committed[n] != fresh[n]}
    assert moved == {}, f"verdicts changed on re-run: {moved}"
    assert committed.keys() == fresh.keys(), (
        f"row set changed: only-committed={sorted(committed.keys() - fresh.keys())}, "
        f"only-fresh={sorted(fresh.keys() - committed.keys())}"
    )


def _load_classifier():
    """Import `classify` from the generator without running it."""
    import importlib.util
    spec = importlib.util.spec_from_file_location("_pine_cov_gen", GEN)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


